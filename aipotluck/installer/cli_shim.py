"""Installs a small `aipotluck-local-client` wrapper onto the system PATH, so the login/logout/
status CLI (aipotluck.installer.cli) is a real command rather than something only reachable from
inside this checkout with `python -m aipotluck.installer.cli`.

Not a pip console-script entry point: this project is never pip-installed -- the installer
downloads prebuilt llama.cpp/newt binaries rather than building anything, and there's no build
step or venv anywhere in this flow for a `[project.scripts]` entry point to hook into. Instead
this writes a tiny wrapper that directly execs the already-resolved Python interpreter against
cli.py's own file path -- the same "invoke the file directly, not via -m" pattern the OS service
registration already uses (ServiceManager.install() is handed aipotluck_service.py's path, not
`-m aipotluck.service.aipotluck_service`) -- which sidesteps needing PYTHONPATH or a specific CWD
for `-m` module resolution to work from an arbitrary shell.
"""

from __future__ import annotations

import ctypes
import logging
import os
import stat
from pathlib import Path

from aipotluck.installer.platform_detect import HostProfile

log = logging.getLogger("aipotluck.installer.cli_shim")

CLI_SHIM_NAME = "aipotluck-local-client"

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
CLI_MODULE_PATH = REPO_ROOT / "aipotluck" / "installer" / "cli.py"


def _bin_dir(profile: HostProfile, system_scope: bool) -> Path:
    if profile.os_name == "windows":
        if system_scope:
            program_files = Path(os.environ.get("ProgramFiles", r"C:\Program Files"))
            return program_files / "aipotluck" / "bin"
        local_appdata = Path(os.environ.get("LOCALAPPDATA", str(Path.home() / "AppData" / "Local")))
        return local_appdata / "aipotluck" / "bin"
    # Linux/macOS: /usr/local/bin is on PATH everywhere without any shell config (why --system
    # uses it, matching --system already assuming elevation for the rest of the install); ~/.local/bin
    # is the standard per-user equivalent but isn't universally on PATH by default (notably not on a
    # bare macOS zsh) -- _ensure_on_path_posix below checks and warns rather than assuming it is.
    if system_scope:
        return Path("/usr/local/bin")
    return Path.home() / ".local" / "bin"


def _posix_shim_text(python_exe: Path) -> str:
    return (
        "#!/usr/bin/env bash\n"
        "# Generated by aipotluck-local-client's installer -- overwritten on every (re)install,\n"
        "# don't hand-edit. Runs the login/logout/status CLI with the exact interpreter the\n"
        "# installer resolved, regardless of what python3 happens to mean in this shell.\n"
        f'exec "{python_exe}" "{CLI_MODULE_PATH}" "$@"\n'
    )


def _windows_shim_text(python_exe: Path) -> str:
    return (
        "@echo off\r\n"
        "REM Generated by aipotluck-local-client's installer -- overwritten on every (re)install,\r\n"
        "REM don't hand-edit.\r\n"
        f'"{python_exe}" "{CLI_MODULE_PATH}" %*\r\n'
    )


PROFILE_BEGIN = "# >>> aipotluck-local-client >>>"
PROFILE_END = "# <<< aipotluck-local-client <<<"

# Startup files that put a directory on PATH for every shell a person is likely to open, written to
# when they already exist: bash login shells read .bash_profile or else .profile, interactive
# non-login bash (most Linux terminals) reads .bashrc, and every zsh reads .zshenv.
_PROFILE_FILES = (".profile", ".bash_profile", ".bashrc", ".zshenv")


def _login_shell() -> str:
    """The user's login shell's name ("zsh", "bash", ...). From the password database, not $SHELL:
    an app started from the desktop (the GUI, a launchd job) may not have SHELL set at all."""
    try:
        import pwd

        return Path(pwd.getpwuid(os.getuid()).pw_shell).name
    except (ImportError, KeyError, OSError):
        return Path(os.environ.get("SHELL", "")).name


def _profile_block(bin_dir: Path) -> str:
    # POSIX sh, so bash, zsh, dash and ksh all accept it; the case guard keeps PATH free of
    # duplicates when several of these files are read by one shell.
    return (
        f"{PROFILE_BEGIN}\n"
        "# Added by the aipotluck-local-client installer so the `aipotluck-local-client` command is\n"
        "# found. Removed by `aipotluck-local-client uninstall`.\n"
        f'case ":$PATH:" in *":{bin_dir}:"*) ;; *) export PATH="{bin_dir}:$PATH" ;; esac\n'
        f"{PROFILE_END}\n"
    )


def _strip_block(text: str) -> str:
    lines, out, inside = text.splitlines(keepends=True), [], False
    for line in lines:
        if line.strip() == PROFILE_BEGIN:
            inside = True
            continue
        if inside:
            if line.strip() == PROFILE_END:
                inside = False
            continue
        out.append(line)
    return "".join(out)


def _profile_targets(home: Path) -> list[Path]:
    """The startup files to put the block in: every one of _PROFILE_FILES that exists, plus the
    one the login shell reads if it has none yet (macOS's default zsh starts with no dotfiles)."""
    targets = [home / name for name in _PROFILE_FILES if (home / name).is_file()]
    shell = _login_shell()
    own = home / (".zshenv" if shell == "zsh" else ".profile" if shell in ("bash", "sh", "dash", "ksh") else "")
    if own.name and own not in targets:
        targets.append(own)
    return targets


def add_to_shell_profiles(bin_dir: Path, home: Path | None = None) -> list[Path]:
    """Puts bin_dir on PATH for new shells by adding a marked block to the user's shell startup
    files (see _profile_targets). Idempotent: an existing block is replaced, never duplicated.
    Returns the files written. Never raises -- an unwritable file is a warning, since the shim
    itself is still installed and reachable by its full path."""
    home = home or Path.home()
    written = []
    for path in _profile_targets(home):
        try:
            old = path.read_text(encoding="utf-8") if path.exists() else ""
            body = _strip_block(old)
            if body and not body.endswith("\n"):
                body += "\n"
            new = body + ("\n" if body.strip() else "") + _profile_block(bin_dir)
            if new != old:
                path.write_text(new, encoding="utf-8")
            written.append(path)
        except OSError as exc:
            log.warning("Could not add %s to PATH in %s (%s)", bin_dir, path, exc)
    if not written:
        log.warning(
            "%s is not on your PATH and no shell startup file could be updated (login shell: %s). "
            'Add this to your shell\'s startup file:\n    export PATH="%s:$PATH"',
            bin_dir, _login_shell() or "unknown", bin_dir,
        )
    else:
        log.info("Added %s to PATH for new shells in %s", bin_dir, ", ".join(str(p) for p in written))
    return written


def remove_from_shell_profiles(home: Path | None = None) -> list[Path]:
    """Removes the block add_to_shell_profiles wrote, from every file that has one. Leaves
    everything else in those files exactly as it was."""
    home = home or Path.home()
    cleaned = []
    for name in _PROFILE_FILES:
        path = home / name
        try:
            old = path.read_text(encoding="utf-8")
        except OSError:
            continue
        if PROFILE_BEGIN not in old:
            continue
        new = _strip_block(old)
        # drop the blank separator line the add left behind, if that's all that's at the end
        if new.endswith("\n\n"):
            new = new[:-1]
        if new.strip():
            path.write_text(new, encoding="utf-8")
        else:
            # Nothing but our block: add_to_shell_profiles created this file (a default macOS
            # account has no .zshenv), so it goes. Found as an empty ~/.zshenv on the Mac mini.
            path.unlink()
        cleaned.append(path)
    return cleaned


def _add_to_user_path_windows(bin_dir: Path) -> bool:
    """Best-effort: prepend bin_dir to HKCU\\Environment\\Path (persistent, no elevation needed)
    and broadcast WM_SETTINGCHANGE so already-open processes that listen for it pick it up --
    the same idiom real Windows installers use. A brand new shell always sees the change
    regardless; the broadcast just spares the *current* one a restart. Never raises -- a failed
    PATH edit is recoverable (the shim file itself is still written) and must not fail the whole
    install over it.

    STUB STATUS: implemented against documented Win32/registry behavior, not exercised on real
    Windows hardware (no Windows host available in this environment) -- same caveat as the rest
    of this repo's Windows path (see aipotluck/installer/python_bootstrap.py,
    aipotluck/installer/service/windows_service.py).
    """
    try:
        import winreg
    except ImportError:
        return False
    try:
        key = winreg.OpenKey(winreg.HKEY_CURRENT_USER, "Environment", 0, winreg.KEY_READ | winreg.KEY_WRITE)
        try:
            try:
                current, _ = winreg.QueryValueEx(key, "Path")
            except FileNotFoundError:
                current = ""
            entries = [e for e in current.split(os.pathsep) if e]
            if str(bin_dir) in entries:
                return True
            winreg.SetValueEx(key, "Path", 0, winreg.REG_EXPAND_SZ, os.pathsep.join([str(bin_dir), *entries]))
        finally:
            winreg.CloseKey(key)

        HWND_BROADCAST, WM_SETTINGCHANGE, SMTO_ABORTIFHUNG = 0xFFFF, 0x1A, 0x0002
        ctypes.windll.user32.SendMessageTimeoutW(
            HWND_BROADCAST, WM_SETTINGCHANGE, 0, "Environment", SMTO_ABORTIFHUNG, 5000, None
        )
        return True
    except OSError as exc:
        log.warning("Could not add %s to your user PATH automatically (%s).", bin_dir, exc)
        return False


def install_cli_shim(profile: HostProfile, python_exe: Path, system_scope: bool) -> Path:
    """Writes the aipotluck-local-client wrapper and returns the path it wrote. Idempotent -- the
    file is fully rewritten every call, matching every other install step here. Best-effort on
    PATH itself: the shim is always written; whether it's *reachable* without an extra step is a
    warning (POSIX per-user, or Windows system-scope, where an automatic registry write needs
    elevation this process doesn't necessarily have) rather than a hard failure."""
    bin_dir = _bin_dir(profile, system_scope)
    bin_dir.mkdir(parents=True, exist_ok=True)

    if profile.os_name == "windows":
        shim_path = bin_dir / f"{CLI_SHIM_NAME}.cmd"
        shim_path.write_text(_windows_shim_text(python_exe), encoding="utf-8", newline="")
        if system_scope:
            log.warning(
                "%s is not necessarily on the machine-wide PATH. Add it via System Properties -> "
                "Environment Variables (System variables -> Path), or from an elevated shell: "
                'setx /M PATH "%%PATH%%;%s"',
                bin_dir, bin_dir,
            )
        elif not _add_to_user_path_windows(bin_dir):
            log.warning(
                "%s is not on your PATH and could not be added automatically. Add it via Settings -> "
                'System -> About -> Advanced system settings -> Environment Variables, or run: '
                'setx PATH "%%PATH%%;%s"',
                bin_dir, bin_dir,
            )
    else:
        shim_path = bin_dir / CLI_SHIM_NAME
        shim_path.write_text(_posix_shim_text(python_exe), encoding="utf-8")
        shim_path.chmod(shim_path.stat().st_mode | stat.S_IEXEC | stat.S_IXGRP | stat.S_IXOTH)
        if not system_scope:  # /usr/local/bin is on PATH everywhere already
            add_to_shell_profiles(bin_dir)

    log.info("Installed %s -> %s", CLI_SHIM_NAME, shim_path)
    return shim_path
